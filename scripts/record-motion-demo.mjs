// Short local review recording. Uses real controls and CSS defaults throughout.
import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
const base=process.env.EVENFORM_URL || 'http://127.0.0.1:5173'
const output=new URL('../evidence/motion-review/',import.meta.url)
await mkdir(output,{recursive:true})
const browser=await chromium.launch()
const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:new URL('recording/',output).pathname,size:{width:1280,height:800}},reducedMotion:'no-preference'})
const page=await context.newPage();page.setDefaultTimeout(8000)
const chapters=[];const start=Date.now()
const chapter=title=>chapters.push({seconds:Number(((Date.now()-start)/1000).toFixed(1)),title})
const pause=ms=>page.waitForTimeout(ms)
const button=name=>page.getByRole('button',{name,exact:true})
try {
  await page.goto(`${base}/#components/motion?anchor=example-motion-tabs`)
  await page.getByRole('tablist',{name:'Project filter',exact:true}).waitFor()
  chapter('Sliding selection');await pause(700)
  for(const name of ['Active','Archived','All projects','Active']){await page.getByRole('tablist',{name:'Project filter',exact:true}).getByRole('tab',{name,exact:true}).click();await pause(500)}
  chapter('Tooltip group')
  for(const name of ['Bold','Italic','Copy text']){await button(name).hover();await pause(650)}
  await page.mouse.move(1200,80)
  chapter('Button feedback')
  await button('Save changes').click();await pause(1100)
  await page.goto(`${base}/#components/motion?anchor=example-motion-morph`)
  await button('Edit project').waitFor();chapter('Morphing popover');await pause(600)
  await button('Edit project').click();await pause(900);await page.keyboard.press('Escape');await pause(400)
  await button('Edit project').click();await pause(500);await button('Cancel').click();await pause(400)
  await page.goto(`${base}/#workspace`)
  await page.getByRole('tablist',{name:'Workspace views',exact:true}).waitFor();chapter('Application view switcher')
  await pause(500);await page.getByRole('tab',{name:'Activity',exact:true}).click();await pause(600)
  await page.getByRole('tab',{name:'Overview',exact:true}).click();await pause(500)
  await button('Move Create your workspace down').scrollIntoViewIfNeeded();await pause(400);chapter('Application checklist')
  await button('Move Create your workspace down').click();await pause(650)
  await button('Move Set up your first project up').click();await pause(650)
  await page.getByRole('checkbox',{name:'Set up your first project',exact:true}).click();await pause(650)
  await page.goto(`${base}/#components/advanced?anchor=example-navigation-menu`)
  await button('Explore library').waitFor();chapter('Navigation content')
  await button('Explore library').click();await pause(700);await button('Guides').hover();await pause(700)
  await button('Guides').focus();await page.keyboard.press('Escape');await pause(350)
  await page.goto(`${base}/#components/advanced?anchor=example-toast`)
  await button('Show notification').waitFor();chapter('Toast stack')
  await button('Show notification').click();await pause(650)
  await button('Notification with undo').click();await pause(650)
  await button('Show notification').click();await pause(700)
  await page.locator('.evenform-toast').first().hover();await pause(250)
  await page.locator('.evenform-toast').first().getByRole('button',{name:'Dismiss notification'}).click();await pause(800)
  await button('Dismiss all').click();await pause(500)
} finally {
  await context.close()
  await page.video().saveAs(new URL('review-interactions.webm',output).pathname)
  await writeFile(new URL('video-chapters.json',output),JSON.stringify(chapters,null,2))
  await browser.close()
}
console.log(JSON.stringify({video:new URL('review-interactions.webm',output).pathname,chapters}))
